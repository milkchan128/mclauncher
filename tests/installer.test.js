const { test } = require('node:test')
const assert = require('node:assert/strict')
const fs = require('fs-extra')
const path = require('node:path')
const { execFileSync, spawnSync } = require('node:child_process')
const { compileSetup, compiler } = require('../scripts/build-windows')

test('전용 설치 창이 업데이트 인수를 전달하고 잘못된 경로·손상된 설치 파일을 거부한다', { skip: process.platform !== 'win32' }, async t => {
    const parent = path.resolve('dist')
    await fs.ensureDir(parent)
    const folder = await fs.mkdtemp(path.join(parent, 'setup-test-'))
    t.after(() => fs.remove(folder))
    const engine = path.join(folder, 'fixture.exe')
    execFileSync(compiler, ['/nologo', '/target:exe', '/out:' + engine, path.resolve('tests/fixtures/FakeInstaller.cs')], { windowsHide: true })
    const setup = path.join(folder, 'setup.exe')
    compileSetup(engine, setup)
    const target = path.join(folder, '설치 경로 with spaces')
    execFileSync(setup, ['/S', '--updated', '--force-run', '/D=' + target], { windowsHide: true, timeout: 30000 })
    assert.equal(await fs.readFile(path.join(target, 'mlkc-Client.exe'), 'utf8'), 'test fixture, never executed')
    assert.deepEqual((await fs.readFile(path.join(target, 'invocation.txt'), 'utf8')).trim().split(/\r?\n/), ['/S', '--updated', '--force-run'])
    const protectedFolder = path.join(folder, 'user files')
    await fs.outputFile(path.join(protectedFolder, 'keep.txt'), 'user data')
    assert.notEqual(spawnSync(setup, ['/S', '/D=' + protectedFolder], { windowsHide: true }).status, 0)
    assert.equal(await fs.readFile(path.join(protectedFolder, 'keep.txt'), 'utf8'), 'user data')
    assert.equal(await fs.pathExists(path.join(protectedFolder, 'invocation.txt')), false)
    await fs.outputFile(path.join(target, 'resources/app.asar'), 'fixture')
    execFileSync(setup, ['/S', '/allusers', '/D=' + target], { windowsHide: true, timeout: 30000 })
    assert.deepEqual((await fs.readFile(path.join(target, 'invocation.txt'), 'utf8')).trim().split(/\r?\n/), ['/S', '/allusers'])
    await fs.outputFile(path.join(target, 'fail-install'), '')
    assert.equal(spawnSync(setup, ['/S', '/D=' + target], { windowsHide: true }).status, 42)
    const bytes = await fs.readFile(setup)
    const payload = await fs.readFile(engine)
    const index = bytes.indexOf(payload)
    assert.ok(index >= 0)
    bytes[index + payload.length - 10] ^= 1
    const damaged = path.join(folder, 'damaged.exe')
    await fs.writeFile(damaged, bytes)
    const untouched = path.join(folder, 'should-not-install')
    assert.notEqual(spawnSync(damaged, ['/S', '/D=' + untouched], { windowsHide: true }).status, 0)
    assert.equal(await fs.pathExists(untouched), false)
})
